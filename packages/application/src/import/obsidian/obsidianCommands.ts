/** La commande de Savoire pour une commande d'Obsidian, ou null (pas d'equivalent). */
export function savoireCommandFor(obsidianId: string): string | null {
  const t = OBSIDIAN_COMMANDS[obsidianId]
  if (t === undefined || typeof t !== 'string') return null
  return t === SAME ? obsidianId : t
}

/** Les commandes d'Obsidian sans equivalent, avec la raison : a faire plus tard, ou sans objet. */
export function obsidianCommandsWithout(kind: 'later' | 'never'): { id: string; why: string }[] {
  return Object.entries(OBSIDIAN_COMMANDS).flatMap(([id, t]) => {
    if (typeof t === 'string') return []
    if (kind === 'later' && 'later' in t) return [{ id, why: t.later }]
    if (kind === 'never' && 'never' in t) return [{ id, why: t.never }]
    return []
  })
}
